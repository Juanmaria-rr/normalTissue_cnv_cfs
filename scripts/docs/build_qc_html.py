#!/usr/bin/env python3
"""Build a self-contained local HTML of the QC levels 1-2 document.

The Claude Docs HTML export (doc_export.html) is a body fragment whose charts are empty
<figure data-embed="node/<id>"> placeholders and whose images point to doc blobs. This
script inlines, as base64 PNG:
  - charts/diagrams: widgets/<node id>.png (screenshots of the published widgets)
  - profile figures: fig_*.png generated by qc_doc_data.R (mapped from blob ids below)
and wraps the fragment in a styled page (light/dark).

Usage:
  python3 scripts/docs/build_qc_html.py --dir docs/qc_levels_1_2 --out docs/qc_levels_1_2/qc_levels_1_2.html
"""
import argparse
import base64
import os
import re

# doc blob id -> figure file written by qc_doc_data.R
BLOB_FIGS = {
    "blob/5c97520a-82b1": "fig_profile_bins_P08_r71c48.png",
    "blob/0d6254bd-b8f6": "fig_profile_depth_200kb.png",
    "blob/c9b89707-f5af": "fig_profile_badfit_P36_r51c33.png",
    "blob/9d034954-b805": "fig_blip_P07_co_r41c34.png",
}

STYLE = """
:root { --bg:#ffffff; --fg:#1f2328; --muted:#59636e; --rule:#d1d9e0; --code:#f6f8fa; --accent:#2563eb; }
@media (prefers-color-scheme: dark) { :root { --bg:#0d1117; --fg:#e6edf3; --muted:#9198a1; --rule:#3d444d; --code:#151b23; --accent:#4c8dff; } }
body { background:var(--bg); color:var(--fg); font:16px/1.6 -apple-system, "Segoe UI", Helvetica, Arial, sans-serif;
       max-width:880px; margin:0 auto; padding:32px 16px 80px; }
h1 { font-size:1.9em; line-height:1.25; } h2 { margin-top:2.2em; padding-bottom:.3em; border-bottom:1px solid var(--rule); }
table { border-collapse:collapse; width:100%; margin:1em 0; font-size:.92em; display:block; overflow-x:auto; }
th, td { border:1px solid var(--rule); padding:6px 10px; text-align:left; vertical-align:top; }
th { background:var(--code); }
code { background:var(--code); padding:.1em .35em; border-radius:4px; font-size:.9em; }
pre { background:var(--code); padding:12px 14px; border-radius:6px; overflow-x:auto; }
pre code { background:none; padding:0; }
img { max-width:100%; height:auto; display:block; margin:1em auto; border-radius:6px; background:#fff; }
figure { margin:1.5em 0; } figcaption { color:var(--muted); font-size:.85em; text-align:center; }
a { color:var(--accent); } em { color:var(--muted); }
"""


# Formulas are exported as ```latex code blocks; render them with KaTeX when online
# (offline, the TeX source stays visible).
KATEX = """
<link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/katex.min.css">
<script defer src="https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/katex.min.js"
  onload="document.querySelectorAll('code.language-latex').forEach(function (c) {
    var d = document.createElement('div');
    katex.render(c.textContent, d, {displayMode: true, throwOnError: false});
    c.parentElement.replaceWith(d); });"></script>
"""


def b64(path):
    with open(path, "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    html = open(os.path.join(a.dir, "doc_export.html"), encoding="utf-8").read()

    def fig(m):
        node, cap = m.group(1), m.group(2)
        png = os.path.join(a.dir, "widgets", f"{node}.png")
        if not os.path.exists(png):
            raise SystemExit(f"missing widget screenshot {png}")
        return f'<figure><img src="{b64(png)}" alt="{cap}"><figcaption>{cap}</figcaption></figure>'
    html, nfig = re.subn(r'<figure data-embed="node/([\w-]+)"><figcaption>(.*?)</figcaption></figure>', fig, html, flags=re.S)

    def img(m):
        src = m.group(1)
        if src not in BLOB_FIGS:
            raise SystemExit(f"unmapped image {src}")
        return f'<img src="{b64(os.path.join(a.dir, BLOB_FIGS[src]))}"'
    html, nimg = re.subn(r'<img src="(blob/[\w-]+)"', img, html)

    # author mention renders as an opaque principal id; drop it
    html = re.sub(r' · <span data-atom="mention"[^>]*>.*?</span>', "", html)
    title = re.search(r"<h1[^>]*>(.*?)</h1>", html).group(1)
    page = (f'<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width, initial-scale=1">'
            f"<title>scDNA-seq QC levels 1-2</title><style>{STYLE}</style>{KATEX}</head>\n<body>\n{html}\n</body></html>\n")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(page)
    print(f"{a.out}: {nfig} charts, {nimg} figures inlined, {len(page) / 1e6:.1f} MB ({title})")


if __name__ == "__main__":
    main()
