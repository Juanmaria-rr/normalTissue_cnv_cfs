md(r"""
# Breakend enrichment at CFS: exploring the master tables and reproducing the tests

**Data lineage.** Each table is produced by a script from the previous one.

| Level | Table | Script |
|---|---|---|
| Metadata (one row per run) | `data/metadata/cells.tsv` | `scripts/00_metadata/` |
| Alignment (one row per cell) | `data/pilot/align_qc_pilot.tsv` | `scripts/02_align/summarize_align_qc.py` |
| CN per bin (R objects) | `results/pilot_cn/relCN/<donor>_<bin>kb/*.rds` | `copynumber` workflow (QDNAseq) |
| QC per cell and bin | `results/pilot_cn/qc/cn_qc_<bin>kb.tsv` | `scripts/03_cn_qc/cn_qc_metrics.R` |
| Segments | `results/pilot_cn/qc/breakends_<bin>kb_segments.tsv` | `scripts/03_cn_qc/call_breakends.R` |
| Breakends and events | `results/enrichment/pilot/{main,nocuts}/{breakends,events}_<bin>kb.tsv` | `scripts/06_enrichment/build_event_table.py` |
| **Master tables** | `results/enrichment/pilot/master_{cells,breakends,events}.tsv` (+ `master_tables.xlsx`) | `scripts/06_enrichment/build_master_tables.py` |
| Test results | `results/enrichment/pilot/main/test_{a,b,c}*.tsv` | `test_a_permutation.py`, `test_b_regression.py`, `test_c_per_donor.py` |

**Master tables:**
- **`master_cells`:** one row per cell × bin, with metadata, alignment and CN QC, `pass_cuts` and the number of breakends.
- **`master_breakends`:** one row per breakend × cell × bin × set (`main` = cells passing the cuts; `nocuts` = `depth_ok` only). It includes the interval, flank ratios, deviation, stratum, direction, type, RT, the event it belongs to, and one `ov:<set>` (0/1) column per catalogue.
- **`master_events`:** one row per collapsed event, with `ov:<set>` and the exact null probability `p:<set>` used by test A.
""")

